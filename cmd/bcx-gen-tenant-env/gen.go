// Command gen generates the broker layer's config from bartixcloud's
// tenants.yml (C2).
//
// One-way flow: tenants.yml -> /etc/bcx-broker/<tenant>.env (one broker per
// tenant with CI repos, plus one for the platform's own CI when it declares a
// `platform.ci` block (G24); a kind:user tenant with empty repos renders none)
// -> /etc/bcx-broker/dispatcher.json (the dispatcher). No broker-layer process
// reads tenants.yml at runtime.
//
// Fails closed: if any row is invalid, nothing is emitted. The authoritative
// validator is infra/fleet/tenants.py; this file checks exactly the fields it
// consumes, so it can never render a half-valid row.
//
// Exit status: 0 ok, 1 --check found drift, 2 invalid input or refused to run.
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const (
	envDir        = "/etc/bcx-broker"
	socketDir     = "/run/bcx-broker"
	tiersFile     = envDir + "/tiers.yml"
	ageKey        = "/etc/bartixcloud/age.key"
	dispatcherMap = "dispatcher.json"
	// generatedMark is the header of every rendered env: the only proof a file
	// in --out is ours to delete.
	generatedMark = "# GENERATED by bcx-gen-tenant-env"
)

const (
	exitOK    = 0
	exitDrift = 1
	exitBad   = 2
)

// staleEnvs lists `<tenant>.env` files in outDir that this render does not
// produce: a tenant that was dropped or renamed, or whose repos went back to []
// (C2). dispatcher.json is rendered on every run, so it can never be stale. A
// directory that does not exist yet has none; one that cannot be read is an
// error, because a stale env left undetected keeps an old broker alive.
func staleEnvs(outDir string, produced rendered) ([]string, error) {
	entries, err := os.ReadDir(outDir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var stale []string
	for _, e := range entries {
		name := e.Name()
		if !strings.HasSuffix(name, ".env") {
			continue
		}
		if _, ok := produced.text(name); !ok {
			stale = append(stale, filepath.Join(outDir, name))
		}
	}
	sort.Strings(stale)
	return stale, nil
}

// isGenerated is true only for a file whose first three lines carry this tool's
// own header.
func isGenerated(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer func() { _ = f.Close() }()
	sc := bufio.NewScanner(f)
	for i := 0; i < 3 && sc.Scan(); i++ {
		if strings.HasPrefix(sc.Text(), generatedMark) {
			return true
		}
	}
	return false
}

// incusProjects returns the project names Incus currently knows. nil, nil means
// Incus is unavailable (not installed, or it refused): the existence rule is
// then skipped, as with --no-incus-check. Incus that answers with something
// that is not a project list is an error: skipping the rule on garbage would
// fail open.
func incusProjects() (map[string]struct{}, error) {
	out, err := exec.Command("incus", "project", "list", "--format", "json").Output()
	if err != nil {
		var exit *exec.ExitError
		if errors.As(err, &exit) || errors.Is(err, exec.ErrNotFound) {
			return nil, nil
		}
		return nil, fmt.Errorf("incus project list: %w", err)
	}
	projects := map[string]struct{}{}
	if len(out) == 0 {
		return projects, nil
	}
	var list []struct {
		Name *string `json:"name"`
	}
	if err := json.Unmarshal(out, &list); err != nil {
		return nil, fmt.Errorf("incus project list: not a JSON list of projects: %w", err)
	}
	for _, p := range list {
		if p.Name == nil || *p.Name == "" {
			return nil, errors.New("incus project list: a project has no name")
		}
		projects[*p.Name] = struct{}{}
	}
	return projects, nil
}

func loadDoc(path string) (*tenantsDoc, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	return parseDoc(data)
}

// writeFile writes text to dir/name through a temp file in the same directory
// and a rename, so a reader never sees a half-written file and every run leaves
// the mode at 0600 whatever the file's previous mode or the umask was.
func writeFile(dir, name, text string) (path string, err error) {
	tmp, err := os.CreateTemp(dir, "."+name+".*.tmp")
	if err != nil {
		return "", err
	}
	defer func() {
		if err != nil {
			_ = os.Remove(tmp.Name())
		}
	}()
	if err = tmp.Chmod(0o600); err != nil {
		_ = tmp.Close()
		return "", err
	}
	if _, err = tmp.WriteString(text); err != nil {
		_ = tmp.Close()
		return "", err
	}
	if err = tmp.Sync(); err != nil {
		_ = tmp.Close()
		return "", err
	}
	if err = tmp.Close(); err != nil {
		return "", err
	}
	path = filepath.Join(dir, name)
	if err = os.Rename(tmp.Name(), path); err != nil {
		return "", err
	}
	return path, nil
}

// console is the process's two output streams. A failing write has nowhere
// left to be reported, so the helpers drop the error on purpose.
type console struct{ stdout, stderr io.Writer }

func (c console) outf(format string, args ...any) { _, _ = fmt.Fprintf(c.stdout, format, args...) }
func (c console) errf(format string, args ...any) { _, _ = fmt.Fprintf(c.stderr, format, args...) }

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr))
}

func run(argv []string, stdout, stderr io.Writer) int {
	c := console{stdout: stdout, stderr: stderr}
	args, err := parseArgs(argv)
	if errors.Is(err, errHelp) {
		c.outf("%s", help)
		return exitOK
	}
	if err != nil {
		c.errf("%s%s: error: %v\n", usage, prog, err)
		return exitBad
	}

	doc, err := loadDoc(args.tenantsYml)
	if err != nil {
		c.errf("%s: %v\n", args.tenantsYml, err)
		return exitBad
	}
	var projects map[string]struct{}
	if !args.noIncusCheck {
		if projects, err = incusProjects(); err != nil {
			c.errf("%v\n", err)
			return exitBad
		}
	}
	files, err := render(doc, projects, args.tenantsYml)
	if err != nil {
		c.errf("%v\n", err)
		return exitBad
	}
	stale, err := staleEnvs(args.out, files)
	if err != nil {
		c.errf("%s: %v\n", args.out, err)
		return exitBad
	}
	if args.check {
		return check(args.out, files, stale, c)
	}
	return write(args.out, files, stale, c)
}

// check re-renders against disk without writing, so a hand-edited file is
// reported as drift rather than silently obeyed.
func check(out string, files rendered, stale []string, c console) int {
	var bad []string
	for _, p := range stale {
		bad = append(bad, p+": not produced by this render (stale)")
	}
	for _, f := range files {
		path := filepath.Join(out, f.Name)
		current, err := os.ReadFile(path)
		if err != nil {
			bad = append(bad, fmt.Sprintf("%s: %v", path, err))
			continue
		}
		if !bytes.Equal(current, []byte(f.Text)) {
			bad = append(bad, path+": differs from generated content")
		}
	}
	for _, b := range bad {
		c.errf("%s\n", b)
	}
	if len(bad) > 0 {
		return exitDrift
	}
	return exitOK
}

func write(out string, files rendered, stale []string, c console) int {
	// Decide before touching anything: a file this tool did not write is never
	// deleted, and its presence stops the run with the directory unchanged.
	var foreign []string
	for _, p := range stale {
		if !isGenerated(p) {
			foreign = append(foreign, p)
		}
	}
	if len(foreign) > 0 {
		for _, p := range foreign {
			c.errf("%s: not produced by this render and not generated by this tool — "+
				"refusing to continue; remove it by hand\n", p)
		}
		return exitBad
	}

	if err := os.MkdirAll(out, 0o755); err != nil {
		c.errf("%v\n", err)
		return exitBad
	}
	for _, f := range files {
		path, err := writeFile(out, f.Name, f.Text)
		if err != nil {
			c.errf("%v\n", err)
			return exitBad
		}
		c.outf("wrote %s\n", path)
	}
	// After the writes, so a failed write never costs a tenant its env. A stale
	// env would keep an enabled bcx-broker@<tenant> on its old repo scope.
	for _, path := range stale {
		if err := os.Remove(path); err != nil {
			c.errf("%v\n", err)
			return exitBad
		}
		c.outf("removed %s\n", path)
	}
	return exitOK
}
